import { readFile, writeFile } from "node:fs/promises";

const postgresSchemaUrl = new URL("../prisma/schema.prisma", import.meta.url);
const d1SchemaUrl = new URL("../prisma/schema.d1.prisma", import.meta.url);

const enumNames = [
	"UserStatus",
	"GameServer",
	"BindingProvider",
	"SnapshotStatus",
	"AliasStatus",
	"CandidateStatus",
	"CandidateRejectionSource",
	"ImportProvider",
	"ImportStatus",
	"MfaChallengePurpose",
];

let schema = await readFile(postgresSchemaUrl, "utf8");
schema = schema.replace(
	/generator client \{[\s\S]*?\}\s*datasource db \{[\s\S]*?\}/u,
	`generator client {
  provider = "prisma-client-js"
  output   = "../generated/d1"
}

datasource db {
  provider = "sqlite"
}`,
);
schema = schema.replace(/enum \w+ \{[\s\S]*?\}\s*/gu, "");
for (const enumName of enumNames) {
	schema = schema.replace(new RegExp(`\\b${enumName}\\??`, "gu"), (match) => (match.endsWith("?") ? "String?" : "String"));
}
schema = schema
	.replace(/String\[\]/gu, "Json")
	.replace(/Json\s+@default\("\{\}"\)/gu, "Json")
	.replace(/\s+@db\.(?:Uuid|Date|Decimal\([^)]*\))/gu, "")
	.replace(
		/@default\((active|disabled|jp|df|lxns|pending|applied|failed|approved|imported|proposed|voting|rejected|manual|login|passkey_registration)\)/gu,
		'@default("$1")',
	);

await writeFile(d1SchemaUrl, `// Generated by scripts/generate-d1-schema.mjs.\n${schema}`);
